const fs = require('fs');
const path = require('path');

const TARGET_DIR = path.join(__dirname, '../src/data/topics');
const INDEX_FILE = path.join(TARGET_DIR, 'index.ts');

function generateIndex() {
  console.log('Scanning topics directory...');
  const files = fs.readdirSync(TARGET_DIR);
  
  const jsonFiles = files.filter(f => f.endsWith('.json'));
  const topics = jsonFiles.map(f => f.replace('.json', ''));

  console.log(`Found topics: ${topics.join(', ')}`);

  const indexContent = `// Automatically generated by generate-vocab-index.cjs
import type { VocabData } from "../../types/vocab";

export const topics = ${JSON.stringify(topics)} as const;
export type Topic = typeof topics[number];

export const loadTopicData = async (topic: string): Promise<VocabData> => {
  switch (topic) {
${jsonFiles.map((file, i) => `    case "${topics[i]}":
      return (await import("./${file}")).default as VocabData;`).join('\n')}
    default:
      throw new Error(\`Unknown topic: \${topic}\`);
  }
};

export const loadAllData = async (): Promise<VocabData[]> => {
  return Promise.all(topics.map(topic => loadTopicData(topic)));
};
`;

  fs.writeFileSync(INDEX_FILE, indexContent);
  console.log('Done!');
}

try {
  generateIndex();
} catch (error) {
  console.error('Error generating vocab index:', error);
  process.exit(1);
}
